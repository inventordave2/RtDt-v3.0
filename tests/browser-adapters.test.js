'use strict';
/* Browser IO adapter tests with fake permissions/downloads; no browser required. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const packNode = require('../rtdt_pack');

const ROOT = path.resolve(__dirname,'..');
const files = {};
const downloads = [];
const cloudUploads = [];
let folderRequested = false;
const fakeDocument = {
    body:{appendChild:function () {}},
    createElement:function (tag) {

        assert.equal(tag,'a');
        return {download:'',href:'',click:function () {

            downloads.push({name:this.download,href:this.href});
        },remove:function () {}};
    }
};
const fakeURL = {
    createObjectURL:function (blob) {

        files.zipBlob = blob;
        return 'blob:mock-output';
    },
    revokeObjectURL:function () {}
};
const sandbox = {
    console:console,
    document:fakeDocument,
    window:{
        isSecureContext:true,
        showDirectoryPicker:async function () {

            folderRequested = true;
            return {
                getFileHandle:async function (name,opts) {

                    assert.equal(opts.create,true);
                    return {
                        createWritable:async function () {

                            return {
                                write:async function (bytes) {

                                    files[name] = Array.from(bytes);
                                },
                                close:async function () {},
                                abort:async function () {

                                    throw new Error('Unexpected abort');
                                }
                            };
                        }
                    };
                }
            };
        }
    },
    URL:fakeURL,
    Blob:Blob,
    TextEncoder:TextEncoder,
    setTimeout:function () { return 1; }
};
vm.createContext(sandbox);
for(const name of ['rtdt_pack.js','rtdt_animation_export.js',
    'rtdt_animation_destination.js','rtdt_animation_storage_browser.js']) {

    vm.runInContext(fs.readFileSync(path.join(ROOT,name),'utf8'),sandbox,
        {filename:name});
}

async function main() {

    const sample = fs.readFileSync(path.join(ROOT,'samples/orbit.rdt'),'utf8');
    const nodeModel = packNode.parse(sample);
    const browserModel = vm.runInContext('rtdt_pack.parse('+JSON.stringify(sample)+')',
        sandbox);
    assert.deepEqual(JSON.parse(JSON.stringify(browserModel)),
        JSON.parse(JSON.stringify(nodeModel)));
    assert.throws(function () {

        vm.runInContext("rtdt_pack.parse('{\"version\":2,\"scene\":\"x.scene\"}')",
            sandbox);
    },/version/);

    // The browser archive bytes are generated by the same ZIP writer used in Node.
    const zipSink = await vm.runInContext(
        "rtdt_animation_storage_browser.create('zip')",sandbox);
    const frameBytes = new Uint8Array([137,80,78,71]);
    await zipSink.add('frame-0000.png',
        vm.runInContext('new Uint8Array([137,80,78,71])',sandbox));
    await zipSink.add('manifest.json',
        vm.runInContext('new Uint8Array([123,125])',sandbox));
    await zipSink.finish();
    assert.equal(downloads.length,1);
    assert.equal(downloads[0].name,'rtdt-animation.zip');
    const zipData = new Uint8Array(await files.zipBlob.arrayBuffer());
    assert.equal(new DataView(zipData.buffer).getUint32(0,true),0x04034b50);

    const folderSink = await vm.runInContext(
        "rtdt_animation_storage_browser.create('folder')",sandbox);
    await folderSink.add('frame-0000.png',
        vm.runInContext('new Uint8Array([137,80,78,71])',sandbox));
    assert.equal(folderRequested,true);
    assert.deepEqual(files['frame-0000.png'],Array.from(frameBytes));
    await folderSink.finish();

    sandbox.window.showDirectoryPicker = null;
    await assert.rejects(vm.runInContext(
        "rtdt_animation_storage_browser.create('folder')",sandbox),
        /Choose ZIP instead/);

    sandbox.rtdt_cloud_auth_browser = {
        get_access_token:async function () { return 'mock'; }
    };
    sandbox.rtdt_cloud_storage = {
        create_writer:async function (name,remotePath,getToken) {

            assert.equal(name,'dropbox');
            assert.equal(remotePath,'RtDt/Testing');
            assert.equal(await getToken(),'mock');
            return async function (filename,bytes) {

                cloudUploads.push({filename,bytes:Array.from(bytes)});
            };
        }
    };
    const cloudSink = await vm.runInContext(
        "rtdt_animation_storage_browser.create('dropbox','RtDt/Testing')",sandbox);
    await cloudSink.add('manifest.json',
        vm.runInContext('new Uint8Array([123,125])',sandbox));
    await cloudSink.finish();
    assert.equal(cloudUploads.length,1);
    assert.deepEqual(cloudUploads[0],{filename:'manifest.json',bytes:[123,125]});

    console.log('Browser pack parser, ZIP, folder permissions and cloud destination adapter passed');
}

main().catch(function (error) {

    console.error(error);
    process.exitCode = 1;
});
